import { cp, mkdir, readFile, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

// Keep the published entry point in sync with its maintainable source files.
await import('./build-standalone.mjs');

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'dist');
const markerName = '.zigzag-static-output';
const markerValue = 'Generated by scripts/build-static.mjs';

let outputExists = true;
try { await stat(output); }
catch (error) {
  if (error.code === 'ENOENT') outputExists = false;
  else throw error;
}

if (outputExists) {
  let marker;
  try { marker = (await readFile(path.join(output, markerName), 'utf8')).trim(); }
  catch { throw new Error('Refusing to replace dist/: it is missing the generated-output marker. Move or rename that folder first.'); }
  if (marker !== markerValue) throw new Error('Refusing to replace dist/: its generated-output marker does not match.');
  await rm(output, { recursive: true, force: true });
}

const sandbox = { window: {} };
vm.runInNewContext(await readFile(path.join(root, 'js/song-manifest.js'), 'utf8'), sandbox, { timeout: 1000 });
const songFiles = sandbox.window.ZIGZAG_SONGS && sandbox.window.ZIGZAG_SONGS.files;
if (!Array.isArray(songFiles) || !songFiles.length || songFiles.some(file => typeof file !== 'string'))
  throw new Error('js/song-manifest.js must provide a non-empty list of song filenames.');

await mkdir(output, { recursive: true });
for (const file of ['index.html', 'LevelEditor.html', 'littlejs.min.js', '.nojekyll'])
  await cp(path.join(root, file), path.join(output, file));
for (const directory of ['css', 'js', 'levels', 'assets'])
  await cp(path.join(root, directory), path.join(output, directory), { recursive: true });

const outputSongs = path.join(output, 'songs');
await mkdir(outputSongs, { recursive: true });
for (const file of songFiles)
  await cp(path.join(root, 'songs', file), path.join(outputSongs, file));

await writeFile(path.join(output, markerName), markerValue + '\n');
process.stdout.write('Static game built in dist/ with only tracks listed in js/song-manifest.js.\n');
